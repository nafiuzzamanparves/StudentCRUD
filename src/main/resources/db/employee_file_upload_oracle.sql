(
    "ID" NUMBER GENERATED ALWAYS AS IDENTITY
        MINVALUE 1
        MAXVALUE 9999999999999999999999999999
        INCREMENT BY 1
        START WITH 1
        CACHE 20
        NOORDER
        NOCYCLE
        NOKEEP
        NOSCALE
        NOT NULL ENABLE,
    "NAME" VARCHAR2(255) NOT NULL ENABLE,
    "EMAIL" VARCHAR2(255) NOT NULL ENABLE,
    "DESIGNATION" VARCHAR2(100),
    "AGE" NUMBER(3,0),
    "ADDRESS" VARCHAR2(500),
    "DOB" DATE,
    "SALARY" NUMBER(10,2),
    "IMAGE" VARCHAR2(255),
    PRIMARY KEY ("ID")
)